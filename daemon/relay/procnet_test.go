func TestParseListeningPortsKeepsOnlyLoopbackAndWildcardListeners(t *testing.T) {
	ipv4 := `  sl  local_address rem_address   st tx_queue rx_queue tr tm->when retrnsmt   uid  timeout inode
   0: 0100007F:1F90 00000000:0000 0A 00000000:00000000 00:00000000 00000000  1000        0 101 1 0000000000000000 100 0 0 10 0
   1: 00000000:0016 00000000:0000 0A 00000000:00000000 00:00000000 00000000     0        0 102 1 0000000000000000 100 0 0 10 0
   2: 0501A8C0:2328 00000000:0000 0A 00000000:00000000 00:00000000 00000000  1000        0 103 1 0000000000000000 100 0 0 10 0
   3: 0100007F:1388 0100007F:9C40 01 00000000:00000000 00:00000000 00000000  1000        0 104 1 0000000000000000 20 4 30 10 -1
`
	ipv6 := `  sl  local_address                         remote_address                        st tx_queue rx_queue tr tm->when retrnsmt   uid  timeout inode
   0: 00000000000000000000000001000000:0BB8 00000000000000000000000000000000:0000 0A 00000000:00000000 00:00000000 00000000  1000        0 201 1 0000000000000000 100 0 0 10 0
   1: 00000000000000000000000000000000:01BB 00000000000000000000000000000000:0000 0A 00000000:00000000 00:00000000 00000000     0        0 202 1 0000000000000000 100 0 0 10 0
   2: 0000000000000000FFFF00000100007F:0FA0 00000000000000000000000000000000:0000 0A 00000000:00000000 00:00000000 00000000  1000        0 203 1 0000000000000000 100 0 0 10 0
   3: 000080FE000000000000000001000000:15B3 00000000000000000000000000000000:0000 0A 00000000:00000000 00:00000000 00000000  1000        0 204 1 0000000000000000 100 0 0 10 0
`
	assertPorts(t, parseListeningPorts(ipv4), 8080, 22)
	assertPorts(t, parseListeningPorts(ipv6), 3000, 443, 4000)
}

func assertPorts(t *testing.T, actual map[int]struct{}, expected ...int) {
	t.Helper()
	want := map[int]struct{}{}
	for _, port := range expected {
		want[port] = struct{}{}
	}
	if !maps.Equal(actual, want) {
		t.Fatalf("ports = %v, want %v", actual, want)
	}
}
